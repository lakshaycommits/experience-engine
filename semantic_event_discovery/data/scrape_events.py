def get_enriched_events() -> list[dict]:
    return ENRICHED_EVENTS


def get_raw_events() -> list[dict]:
    raw_fields = {
        "id", "title", "venue", "area", "city", "date", "time", "end_time",
        "category", "subcategory", "price_min", "price_max", "description",
        "age_restriction", "tags", "organizer",
    }
    return [{k: v for k, v in e.items() if k in raw_fields} for e in ENRICHED_EVENTS]


def save_to_disk():
    raw = get_raw_events()
    enriched = get_enriched_events()

    with open(DATA_DIR / "raw_events.json", "w") as f:
        json.dump(raw, f, indent=2, ensure_ascii=False)
    print(f"Saved {len(raw)} raw events to raw_events.json")

    with open(DATA_DIR / "enriched_events.json", "w") as f:
        json.dump(enriched, f, indent=2, ensure_ascii=False)
    print(f"Saved {len(enriched)} enriched events to enriched_events.json")


if __name__ == "__main__":
    save_to_disk()
